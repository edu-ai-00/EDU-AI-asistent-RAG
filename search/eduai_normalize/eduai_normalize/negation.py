"""Which folded lemmas are a NEGATION the lemmatizer made — the language data for
the polarity check of the curated-QA match (search/app/nodes/qa_common.py).

The lemmatizer keeps a Czech negation in the lemma ("nesmím" → nesmět,
lemmatizer._lemma_known); the tokens that reach the search are folded to
ASCII. A test on the folded token alone cannot tell a negation from a word that
merely starts with the letters: "někdy" folds to `nekdy` like "ne-kdy",
"nemoc" reads as "ne-moc". The lemmatizer can, because it decides on the word
with its diacritics. This module asks it once, over every form of the
dictionary, and keeps the folded lemmas it produced AS A NEGATION. A token is a
negation exactly when it is in that set — `nesmet`, `nemit`, `nemoci`
("nemůžu"), `nebyt`; not `nemoc`, `nekdy`, `nekolik`, `nejak`, `nedele`.

The set is generated, never edited by hand (2.3 s to load the dictionary and 5 s
to scan it, too slow for every process start):

    python -m eduai_normalize.negation --write     # rewrites _negated_lemmas.py
    python -m eduai_normalize.negation --check     # exit 1 when it is stale

A language without a negation prefix (en, de, es: a separate word negates)
has an empty set.
"""

from __future__ import annotations

import argparse
import os
import sys

from .lemmatizer import NEGATION_PREFIX, _NEGATION_EXCEPTIONS, _base_lemma
from .normalize import fold

try:
    from ._negated_lemmas import NEGATED_LEMMAS
except ImportError:                      # before the first --write
    NEGATED_LEMMAS = {}

_EMPTY: frozenset = frozenset()


def negated_lemmas(lang: str | None) -> frozenset:
    """The folded negated lemmas of `lang`; None = of every language."""
    if lang:
        return NEGATED_LEMMAS.get(lang, _EMPTY)
    return frozenset().union(*NEGATED_LEMMAS.values()) if NEGATED_LEMMAS else _EMPTY


def is_negation(token: str, lang: str | None) -> bool:
    """True when `token` (a folded lemma) is a negation the lemmatizer makes."""
    if lang:
        return token in NEGATED_LEMMAS.get(lang, _EMPTY)
    return any(token in s for s in NEGATED_LEMMAS.values())


def build(lang: str) -> frozenset:
    """Scan simplemma's dictionary of `lang`: every form the lemmatizer reduces to
    prefix + lemma (the negation branch of lemmatizer._lemma_known), folded, plus
    the forms the prefix test cannot recognise (_NEGATION_EXCEPTIONS)."""
    prefixes = NEGATION_PREFIX.get(lang, ())
    out = {fold(v) for v in _NEGATION_EXCEPTIONS.get(lang, {}).values()}
    if not prefixes:
        return frozenset(out)
    from simplemma.strategies.dictionaries.dictionary_factory import DefaultDictionaryFactory
    forms = DefaultDictionaryFactory().get_dictionary(lang).keys()
    for k in forms:
        wl = (k.decode() if isinstance(k, bytes) else k).lower()
        for p in prefixes:
            if len(wl) <= len(p) + 1 or not wl.startswith(p):
                continue
            lemma = _base_lemma(wl, lang)
            if (not lemma.lower().startswith(p)
                    and fold(_base_lemma(wl[len(p):], lang)) == fold(lemma)):
                out.add(fold(p + lemma))
    return frozenset(out)


def _render(data: dict[str, frozenset]) -> str:
    lines = ['"""GENERATED by `python -m eduai_normalize.negation --write`; do not edit.',
             "",
             "Folded lemmas the lemmatizer produces as a negation, per language (see negation.py).",
             '"""', "", "NEGATED_LEMMAS = {"]
    for lang in sorted(data):
        words = sorted(data[lang])
        lines.append(f"    {lang!r}: frozenset({{")
        for i in range(0, len(words), 8):
            lines.append("        " + " ".join(f"{w!r}," for w in words[i:i + 8]))
        lines.append("    }),")
    lines.append("}")
    return "\n".join(lines) + "\n"


def _target() -> str:
    return os.path.join(os.path.dirname(os.path.abspath(__file__)), "_negated_lemmas.py")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true", help="regenerate _negated_lemmas.py")
    g.add_argument("--check", action="store_true", help="exit 1 when the shipped set is stale")
    a = ap.parse_args(argv)
    text = _render({lang: build(lang) for lang in sorted(NEGATION_PREFIX)})
    if a.write:
        with open(_target(), "w", encoding="utf-8") as fh:
            fh.write(text)
        print(f"written {_target()}", file=sys.stderr)
        return 0
    try:
        with open(_target(), encoding="utf-8") as fh:
            same = fh.read() == text
    except FileNotFoundError:
        same = False
    print("negated lemmas: " + ("up to date" if same else "STALE — run --write"), file=sys.stderr)
    return 0 if same else 1


if __name__ == "__main__":
    sys.exit(main())
