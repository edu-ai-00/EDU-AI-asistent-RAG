"""Which folded lemmas are a NEGATION the lemmatizer made — the language data for
the polarity check of the curated-QA match (search/app/nodes/qa_common.py).

The lemmatizer keeps a Czech negation in the lemma ("nesmím" → nesmět,
lemmatizer._lemma_known); the tokens that reach the search are folded to
ASCII. A test on the folded token alone cannot tell a negation from a word that
merely starts with the letters: "někdy" folds to `nekdy` like "ne-kdy",
"nemoc" reads as "ne-moc". The lemmatizer can, because it decides on the word
with its diacritics. This module asks it once, over every form of the
dictionary, and keeps the folded lemmas it produced AS A NEGATION. A token is a
negation exactly when it is in that set — `nesmet`, `nemit`, `nemoci`
("nemůžu"), `nebyt`; not `nemoc`, `nekdy`, `nekolik`, `nejak`, `nedele`.

The set is generated by negation_build.py, never edited by hand (2.3 s to load
the dictionary and 5 s to scan it, too slow for every process start; the command
is in AGENTS.md). A missing set is an import error, not a silently disabled
check: the file ships with the package.

A language without a negation prefix (en, de, es: a separate word negates)
has an empty set.
"""

from __future__ import annotations

from ._negated_lemmas import NEGATED_LEMMAS
from .normalize import fold

_EMPTY: frozenset = frozenset()


def negated_lemmas(lang: str | None) -> frozenset:
    """The folded negated lemmas of `lang`; None = of every language."""
    if lang:
        return NEGATED_LEMMAS.get(lang, _EMPTY)
    return frozenset().union(*NEGATED_LEMMAS.values()) if NEGATED_LEMMAS else _EMPTY


def is_negation(token: str, lang: str | None) -> bool:
    """True when `token` (a lemma) is a negation the lemmatizer makes. The token is
    folded first: the set is folded, and a school that keeps diacritics in its
    tokens (normalization.strip_diacritics false) must not lose the check."""
    t = fold(token or "")
    if lang:
        return t in NEGATED_LEMMAS.get(lang, _EMPTY)
    return any(t in s for s in NEGATED_LEMMAS.values())
