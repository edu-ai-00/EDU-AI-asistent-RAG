"""Generator of _negated_lemmas.py, the set negation.is_negation reads.

Not imported by the package: it scans simplemma's dictionary, which only this
generator needs.

    python -m eduai_normalize.negation_build --write   # rewrite _negated_lemmas.py
    python -m eduai_normalize.negation_build --check   # exit 1 when it is stale

Run it where `eduai_normalize` resolves to the SOURCE checkout (the command in
AGENTS.md copies the package into the search container and back), not to an
installed copy: --write rewrites the file next to this module.
"""

from __future__ import annotations

import argparse
import os
import sys

from .lemmatizer import NEGATION_PREFIX, _NEGATION_EXCEPTIONS, _base_lemma
from .normalize import fold


def build(lang: str) -> frozenset:
    """Scan simplemma's dictionary of `lang`: every form the lemmatizer reduces to
    prefix + lemma (the negation branch of lemmatizer._lemma_known), folded, plus
    the forms the prefix test cannot recognise (_NEGATION_EXCEPTIONS)."""
    prefixes = NEGATION_PREFIX.get(lang, ())
    out = {fold(v) for v in _NEGATION_EXCEPTIONS.get(lang, {}).values()}
    if not prefixes:
        return frozenset(out)
    from simplemma.strategies.dictionaries.dictionary_factory import DefaultDictionaryFactory
    forms = DefaultDictionaryFactory().get_dictionary(lang).keys()
    for k in forms:
        wl = (k.decode() if isinstance(k, bytes) else k).lower()
        for p in prefixes:
            if len(wl) <= len(p) + 1 or not wl.startswith(p):
                continue
            lemma = _base_lemma(wl, lang)
            if (not lemma.lower().startswith(p)
                    and fold(_base_lemma(wl[len(p):], lang)) == fold(lemma)):
                out.add(fold(p + lemma))
    return frozenset(out)


def _render(data: dict[str, frozenset]) -> str:
    lines = ['"""GENERATED by `python -m eduai_normalize.negation_build --write`; do not edit.',
             "",
             "Folded lemmas the lemmatizer produces as a negation, per language (see negation.py).",
             '"""', "", "NEGATED_LEMMAS = {"]
    for lang in sorted(data):
        words = sorted(data[lang])
        lines.append(f"    {lang!r}: frozenset({{")
        for i in range(0, len(words), 8):
            lines.append("        " + " ".join(f"{w!r}," for w in words[i:i + 8]))
        lines.append("    }),")
    lines.append("}")
    return "\n".join(lines) + "\n"


def _target() -> str:
    return os.path.join(os.path.dirname(os.path.abspath(__file__)), "_negated_lemmas.py")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true", help="regenerate _negated_lemmas.py")
    g.add_argument("--check", action="store_true", help="exit 1 when the shipped set is stale")
    a = ap.parse_args(argv)
    text = _render({lang: build(lang) for lang in sorted(NEGATION_PREFIX)})
    if a.write:
        with open(_target(), "w", encoding="utf-8") as fh:
            fh.write(text)
        print(f"written {_target()}", file=sys.stderr)
        return 0
    try:
        with open(_target(), encoding="utf-8") as fh:
            same = fh.read() == text
    except FileNotFoundError:
        same = False
    print("negated lemmas: " + ("up to date" if same else "STALE — regenerate it (command in AGENTS.md)"),
          file=sys.stderr)
    return 0 if same else 1


if __name__ == "__main__":
    sys.exit(main())
