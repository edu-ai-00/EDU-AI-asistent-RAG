"""Emit SQL that restores human-declared document metadata from an inventory export.

Re-ingesting a corpus rebuilds content but not declarations: the gateway derives
document_type/domain/grade with the LLM, so school_grade_user, document_domain_user,
document_type_user and valid_from/to come back empty or different. This turns an
inventory JSON (codes, not ids) into an UPDATE that puts them back.

    python scripts/restore_declared_metadata.py inventory.json > restore.sql
    docker compose exec -T postgres psql -U edu_ai_admin -d edu_ai -v ON_ERROR_STOP=1 < restore.sql

Two things the generated SQL is careful about, both of which fail silently otherwise:

  * ids are never carried across databases. Codes are resolved in the target DB, and
    the číselníky are per-tenant — a school_grade code like '9999' exists once per
    legal_entity plus a global row, so an unscoped lookup picks a neighbour's id.
    Resolution therefore prefers the document's own entity and falls back to global.
  * document_domain_user / school_grade_user are bigint[], and Postgres cannot put a
    foreign key on array elements. A wrong id does not raise — it silently relabels
    the document. So the script re-reads what it wrote and compares it back to the
    inventory, and the transaction aborts on the first mismatch.

Documents are matched on source_url: re-ingestion mints fresh file_uuids, so the
inventory's uuids are meaningless in the target. Entries without a source_url cannot
be matched and are reported, not guessed.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

# Inventory field -> what it means here. The *_llm fields are included because an
# inventory records what the LLM actually decided for that document; re-deriving
# them would give a different answer for no benefit.
ARRAY_CODE_FIELDS = {
    "school_grades_declared": "school_grade_user",
    "domains_declared": "document_domain_user",
    "domains_llm": "document_domain_llm",
}
TEXT_FIELDS = {
    "document_type_user": "document_type_user",
    "document_type_llm": "document_type_llm",
    "language_user": "document_language_user",
    "language_llm": "document_language_llm",
    "title": "document_header",
}
DATE_FIELDS = {"valid_from": "valid_from", "valid_to": "valid_to"}


def lit(value: str | None) -> str:
    """A SQL string literal, or NULL."""
    if value is None:
        return "NULL"
    return "'" + str(value).replace("'", "''") + "'"


def arr(values: list[str] | None) -> str:
    """A text[] literal, or NULL. Empty list is NULL, not '{}' — an empty array and
    'not declared' mean the same thing here and NULL is what the column holds."""
    if not values:
        return "NULL"
    return "ARRAY[" + ", ".join(lit(v) for v in values) + "]::text[]"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("inventory", type=pathlib.Path,
                        help="inventory JSON: {\"documents\": [...]} with codes, not ids")
    parser.add_argument("--skip-no-url", action="store_true",
                        help="omit entries without source_url instead of failing")
    args = parser.parse_args()

    # The emitted SQL carries Czech document titles, so it has to leave here as UTF-8
    # whatever the console's codepage is — on Windows that default is cp1250 and even
    # the box-drawing in the comments is enough to abort the write.
    sys.stdout.reconfigure(encoding="utf-8")

    payload = json.loads(args.inventory.read_text(encoding="utf-8"))
    docs = payload["documents"] if isinstance(payload, dict) else payload

    usable, no_url = [], []
    for doc in docs:
        (usable if doc.get("source_url") else no_url).append(doc)

    if no_url and not args.skip_no_url:
        for doc in no_url:
            print(f"-- NO source_url, cannot match: {doc.get('file_name')}", file=sys.stderr)
        print(f"error: {len(no_url)} entr(ies) have no source_url — re-upload them by hand "
              f"or pass --skip-no-url", file=sys.stderr)
        return 1

    seen: dict[str, str] = {}
    for doc in usable:
        url = doc["source_url"]
        if url in seen:
            print(f"error: source_url is not unique in the inventory, so it cannot be a "
                  f"match key: {url}", file=sys.stderr)
            return 1
        seen[url] = doc["legal_entity"]

    out = print
    out("-- Generated by scripts/restore_declared_metadata.py — review before running.")
    out(f"-- Source: {args.inventory.name}  ({len(usable)} matchable"
        + (f", {len(no_url)} skipped for having no source_url" if no_url else "") + ")")
    for doc in no_url:
        out(f"--   skipped (no source_url): {doc.get('file_name')}")
    out("")
    out("\\set ON_ERROR_STOP on")
    out("BEGIN;")
    out("")
    out("CREATE TEMP TABLE want (")
    out("  source_url    text PRIMARY KEY,")
    out("  entity        text NOT NULL,")
    out("  grades        text[],")
    out("  domains_user  text[],")
    out("  domains_llm   text[],")
    out("  roles         text[],")
    out("  doctype_user  text,")
    out("  doctype_llm   text,")
    out("  lang_user     text,")
    out("  lang_llm      text,")
    out("  header        text,")
    out("  valid_from    date,")
    out("  valid_to      date")
    out(") ON COMMIT DROP;")
    out("")
    out("INSERT INTO want VALUES")
    rows = []
    for doc in usable:
        rows.append("  (" + ", ".join([
            lit(doc["source_url"]),
            lit(doc["legal_entity"]),
            arr(doc.get("school_grades_declared")),
            arr(doc.get("domains_declared")),
            arr(doc.get("domains_llm")),
            arr(doc.get("audience_roles")),
            lit(doc.get("document_type_user")),
            lit(doc.get("document_type_llm")),
            lit(doc.get("language_user")),
            lit(doc.get("language_llm")),
            lit(doc.get("title")),
            lit(doc.get("valid_from")),
            lit(doc.get("valid_to")),
        ]) + ")")
    out(",\n".join(rows) + ";")
    out("")

    out(r"""
-- ── 1. every inventory row must match exactly one live document ──────────────
\echo
\echo -- match check (rows below are problems; empty is good)
SELECT w.source_url,
       count(d.file_uuid) AS matches,
       string_agg(DISTINCT d.legal_entity_code, ',') AS entities_found
  FROM want w
  LEFT JOIN edu_ai.document_metadata d
         ON d.source_url = w.source_url AND d.is_active
 GROUP BY w.source_url
HAVING count(d.file_uuid) <> 1
 ORDER BY 2, 1;

DO $$
DECLARE bad int;
BEGIN
  SELECT count(*) INTO bad FROM (
    SELECT w.source_url FROM want w
      LEFT JOIN edu_ai.document_metadata d
             ON d.source_url = w.source_url AND d.is_active
     GROUP BY w.source_url HAVING count(d.file_uuid) <> 1) t;
  IF bad > 0 THEN
    RAISE EXCEPTION '% inventory row(s) do not match exactly one active document — '
                    'ingest first, or fix the inventory. Nothing was written.', bad;
  END IF;
END $$;

-- ── 2. every code must resolve, at the document's entity or globally ─────────
\echo
\echo -- unresolvable codes (rows below are problems; empty is good)
WITH g AS (
  SELECT w.source_url, w.entity, 'school_grade' AS kind, c.code
    FROM want w, unnest(w.grades) AS c(code)
   WHERE NOT EXISTS (SELECT 1 FROM edu_ai.code_list x
                      WHERE x.list_code='school_grade' AND x.is_active AND x.code=c.code
                        AND (x.legal_entity_code = w.entity OR x.legal_entity_code IS NULL))
), d AS (
  SELECT w.source_url, w.entity, 'DOMAIN', c.code
    FROM want w, unnest(w.domains_user || w.domains_llm) AS c(code)
   WHERE NOT EXISTS (SELECT 1 FROM edu_ai.taxonomy_rules x
                      WHERE x.taxonomy_type_code='DOMAIN' AND x.is_active AND x.type_code=c.code
                        AND (x.legal_entity_code = w.entity OR x.legal_entity_code IS NULL))
), t AS (
  SELECT w.source_url, w.entity, 'DOCUMENT_TYPE', c.code
    FROM want w, unnest(ARRAY[w.doctype_user, w.doctype_llm]) AS c(code)
   WHERE c.code IS NOT NULL
     AND NOT EXISTS (SELECT 1 FROM edu_ai.taxonomy_rules x
                      WHERE x.taxonomy_type_code='DOCUMENT_TYPE' AND x.is_active
                        AND x.type_code=c.code
                        AND (x.legal_entity_code = w.entity OR x.legal_entity_code IS NULL))
)
SELECT * FROM g UNION ALL SELECT * FROM d UNION ALL SELECT * FROM t;

DO $$
DECLARE bad int;
BEGIN
  SELECT count(*) INTO bad
    FROM want w, unnest(w.grades) AS c(code)
   WHERE NOT EXISTS (SELECT 1 FROM edu_ai.code_list x
                      WHERE x.list_code='school_grade' AND x.is_active AND x.code=c.code
                        AND (x.legal_entity_code = w.entity OR x.legal_entity_code IS NULL));
  IF bad > 0 THEN RAISE EXCEPTION '% grade code(s) do not resolve. Nothing written.', bad; END IF;
  SELECT count(*) INTO bad
    FROM want w, unnest(w.domains_user || w.domains_llm) AS c(code)
   WHERE NOT EXISTS (SELECT 1 FROM edu_ai.taxonomy_rules x
                      WHERE x.taxonomy_type_code='DOMAIN' AND x.is_active AND x.type_code=c.code
                        AND (x.legal_entity_code = w.entity OR x.legal_entity_code IS NULL));
  IF bad > 0 THEN RAISE EXCEPTION '% domain code(s) do not resolve. Nothing written.', bad; END IF;
END $$;

-- ── 3. write it back ────────────────────────────────────────────────────────
-- `IS NOT DISTINCT FROM`, not `=`, in the ORDER BY: for a global row the comparison
-- to the entity is NULL, and DESC sorts NULLs FIRST in Postgres — which would prefer
-- the global row over the document's own entity, exactly backwards.
UPDATE edu_ai.document_metadata d SET
  school_grade_user = CASE WHEN w.grades IS NULL THEN d.school_grade_user ELSE (
      SELECT array_agg(r.id ORDER BY g.ord)
        FROM unnest(w.grades) WITH ORDINALITY AS g(code, ord)
        CROSS JOIN LATERAL (
          SELECT c.id FROM edu_ai.code_list c
           WHERE c.list_code='school_grade' AND c.is_active AND c.code = g.code
             AND (c.legal_entity_code = w.entity OR c.legal_entity_code IS NULL)
           ORDER BY (c.legal_entity_code IS NOT DISTINCT FROM w.entity) DESC, c.id
           LIMIT 1) r) END,
  document_domain_user = CASE WHEN w.domains_user IS NULL THEN d.document_domain_user ELSE (
      SELECT array_agg(r.id ORDER BY x.ord)
        FROM unnest(w.domains_user) WITH ORDINALITY AS x(code, ord)
        CROSS JOIN LATERAL (
          SELECT t.id FROM edu_ai.taxonomy_rules t
           WHERE t.taxonomy_type_code='DOMAIN' AND t.is_active AND t.type_code = x.code
             AND (t.legal_entity_code = w.entity OR t.legal_entity_code IS NULL)
           ORDER BY (t.legal_entity_code IS NOT DISTINCT FROM w.entity) DESC, t.id
           LIMIT 1) r) END,
  document_domain_llm = CASE WHEN w.domains_llm IS NULL THEN d.document_domain_llm ELSE (
      SELECT array_agg(r.id ORDER BY x.ord)
        FROM unnest(w.domains_llm) WITH ORDINALITY AS x(code, ord)
        CROSS JOIN LATERAL (
          SELECT t.id FROM edu_ai.taxonomy_rules t
           WHERE t.taxonomy_type_code='DOMAIN' AND t.is_active AND t.type_code = x.code
             AND (t.legal_entity_code = w.entity OR t.legal_entity_code IS NULL)
           ORDER BY (t.legal_entity_code IS NOT DISTINCT FROM w.entity) DESC, t.id
           LIMIT 1) r) END,
  audience_roles         = coalesce(w.roles,        d.audience_roles),
  document_type_user     = coalesce(w.doctype_user, d.document_type_user),
  document_type_llm      = coalesce(w.doctype_llm,  d.document_type_llm),
  document_language_user = coalesce(w.lang_user,    d.document_language_user),
  document_language_llm  = coalesce(w.lang_llm,     d.document_language_llm),
  document_header        = coalesce(w.header,       d.document_header),
  valid_from             = coalesce(w.valid_from,   d.valid_from),
  valid_to               = coalesce(w.valid_to,     d.valid_to)
FROM want w
WHERE d.source_url = w.source_url AND d.is_active;

-- ── 4. round-trip: read the ids back as codes and compare to the inventory ──
-- The array columns have no foreign key (Postgres cannot constrain array elements),
-- so a wrong id would not raise. This is the only thing that actually proves it.
\echo
\echo -- round-trip mismatches (rows below are problems; empty is good)
WITH back AS (
  SELECT w.source_url, w.entity,
         (SELECT array_agg(c.code ORDER BY u.ord)
            FROM unnest(d.school_grade_user) WITH ORDINALITY AS u(id, ord)
            JOIN edu_ai.code_list c ON c.id = u.id) AS grades_back,
         (SELECT array_agg(t.type_code ORDER BY u.ord)
            FROM unnest(d.document_domain_user) WITH ORDINALITY AS u(id, ord)
            JOIN edu_ai.taxonomy_rules t ON t.id = u.id) AS domains_back,
         w.grades, w.domains_user,
         d.document_type_user, w.doctype_user
    FROM want w
    JOIN edu_ai.document_metadata d
      ON d.source_url = w.source_url AND d.is_active
)
SELECT source_url, entity, grades, grades_back, domains_user, domains_back
  FROM back
 WHERE coalesce(grades_back, '{}') IS DISTINCT FROM coalesce(grades, '{}')
    OR coalesce(domains_back, '{}') IS DISTINCT FROM coalesce(domains_user, '{}')
    OR document_type_user IS DISTINCT FROM coalesce(doctype_user, document_type_user);

DO $$
DECLARE bad int;
BEGIN
  SELECT count(*) INTO bad FROM want w
    JOIN edu_ai.document_metadata d ON d.source_url = w.source_url AND d.is_active
   WHERE coalesce((SELECT array_agg(c.code ORDER BY u.ord)
                     FROM unnest(d.school_grade_user) WITH ORDINALITY AS u(id, ord)
                     JOIN edu_ai.code_list c ON c.id = u.id), '{}')
         IS DISTINCT FROM coalesce(w.grades, '{}')
      OR coalesce((SELECT array_agg(t.type_code ORDER BY u.ord)
                     FROM unnest(d.document_domain_user) WITH ORDINALITY AS u(id, ord)
                     JOIN edu_ai.taxonomy_rules t ON t.id = u.id), '{}')
         IS DISTINCT FROM coalesce(w.domains_user, '{}');
  IF bad > 0 THEN
    RAISE EXCEPTION 'round-trip failed on % document(s): the ids written do not read '
                    'back as the inventory codes. Rolled back.', bad;
  END IF;
  RAISE NOTICE 'round-trip OK — every id reads back as the code it came from';
END $$;

\echo
\echo -- what changed
SELECT count(*) AS documents_updated,
       count(*) FILTER (WHERE d.school_grade_user IS NOT NULL) AS with_grades,
       count(*) FILTER (WHERE d.document_domain_user IS NOT NULL) AS with_domains,
       count(*) FILTER (WHERE d.document_type_user IS NOT NULL) AS with_doctype
  FROM want w JOIN edu_ai.document_metadata d
    ON d.source_url = w.source_url AND d.is_active;

COMMIT;
""")
    return 0


if __name__ == "__main__":
    sys.exit(main())
