-- 47_ui_label.sql
-- edu_ai.ui_label — user-interface copy as DATA, per language, like every other
-- user-facing string in this system (system_message, prompt_registry, code_list).
--
-- Why its own table and not system_message: that one is PRODUCT copy shipped to
-- learners inside an answer (no_answer, guard_self_harm with Linka bezpečí). UI
-- chrome is a different audience and lifecycle, it is an order of magnitude more
-- rows, and it needs a real `scope` column — encoding the scope in a key prefix
-- and querying it with LIKE would be a convention the database cannot enforce.
--
-- The contract the pages rely on:
--   * the language MENU is the intersection of the active languages in
--     code_list('language') and the languages that have EVERY key of that scope —
--     a language that cannot be fully rendered is not offered at all;
--   * the DEFAULT is code_list.is_ui_default, if it is in that menu;
--   * adding a language is INSERTs here, no code change (docs/ADDING_A_LANGUAGE.md).
--
-- Czech is lifted verbatim from the pages as they were. English, German and
-- Spanish are translations and want a human check — this is copy a user reads,
-- not a fact derived from data.
--
-- Idempotent (ON CONFLICT DO NOTHING on the active unique index); transactional.

BEGIN;

CREATE TABLE IF NOT EXISTS edu_ai.ui_label (
    id          bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    scope       text        NOT NULL,
    label_key   text        NOT NULL,
    lang        text        NOT NULL,
    label_text  text        NOT NULL,
    is_active   boolean     NOT NULL DEFAULT true,
    created_at  timestamptz NOT NULL DEFAULT now(),
    notes       text
);

COMMENT ON TABLE edu_ai.ui_label IS
    'Interface copy per language and scope. A language is offered in a page''s '
    'switcher only when it has every key of that scope.';

CREATE UNIQUE INDEX IF NOT EXISTS ui_label_active
    ON edu_ai.ui_label (scope, label_key, lang) WHERE is_active;
CREATE INDEX IF NOT EXISTS ui_label_scope_idx
    ON edu_ai.ui_label (scope) WHERE is_active;

